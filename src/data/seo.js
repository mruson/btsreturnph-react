// One entry per route. This single file feeds three things:
//   1. The browser tab title + meta description while you click around the site
//      (src/lib/seo.js).
//   2. The static HTML that Facebook / X / Threads / Viber crawlers read when
//      someone pastes a link (scripts/prerender-seo.mjs, runs on `npm run build`).
//   3. sitemap.xml (same script).
//
// Keep `title` under ~60 characters and `description` under ~160 — longer text
// gets truncated with an ellipsis in search results and share cards.

// Canonical origin, no trailing slash — social crawlers need absolute og:url
// and og:image values, so everything is built from this.
//
// Production always uses the real domain: canonical tags must never point at a
// *.netlify.app address or search engines will treat that as the real site.
// Only deploy previews and branch deploys advertise their own URL, so a preview
// unfurls as itself instead of claiming to be production.
//
// The APEX, not www. Netlify serves the site from btsreturnph.com and 301s
// www → apex, so naming www here pointed every canonical tag, og:url and
// sitemap entry at a URL that redirects. Search engines follow it, but a
// canonical should name the address that actually answers 200.
const CANONICAL = 'https://btsreturnph.com'

// The `typeof` guard matters — this file is imported by the browser bundle too,
// where `process` doesn't exist. Vite compiles the check away to a constant.
const env = typeof process !== 'undefined' ? process.env || {} : {}
const previewUrl =
  env.CONTEXT && env.CONTEXT !== 'production'
    ? env.DEPLOY_PRIME_URL || env.URL || ''
    : ''

export const siteUrl = (previewUrl || CANONICAL).replace(/\/$/, '')

