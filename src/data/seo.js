// Resolve a pathname to a complete SEO record (relative image path).
export function seoFor(pathname) {
  const entry = routeSeo[pathname] || {}
  return {
    title: entry.title || defaultSeo.title,
    description: entry.description || defaultSeo.description,
    image: entry.image || defaultSeo.image,
    noindex: entry.noindex || !routeSeo[pathname], // unknown routes (404) aren't indexed
  }
}
